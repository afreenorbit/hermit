/** Tilli, animated. Owner: C. The drawing lives in ../mascot/tilli.ts. */
import { useMemo, type CSSProperties } from 'react';

import { tilliSvg, type TilliMood } from '../mascot/tilli';

export interface TilliProps {
  mood?: TilliMood;
  /** Rendered width in CSS px. */
  size?: number;
  /** Face left instead of right. */
  flip?: boolean;
  /** Eye direction, each -1..1. */
  look?: readonly [number, number];
  letter?: boolean;
  marks?: boolean;
  /** Freeze on the first pose (thumbnails, reduced motion is automatic). */
  still?: boolean;
  label?: string;
  className?: string;
  style?: CSSProperties;
}

export function Tilli({
  mood = 'happy',
  size = 160,
  flip,
  look,
  letter,
  marks = true,
  still,
  label = 'Tilli',
  className,
  style,
}: TilliProps) {
  const html = useMemo(
    () => tilliSvg({ mood, letter, marks, title: label }),
    [mood, letter, marks, label],
  );
  const vars = {
    width: size,
    height: size,
    '--tilli-look-x': look?.[0] ?? 0,
    '--tilli-look-y': look?.[1] ?? 0,
    ...style,
  } as CSSProperties;
  return (
    <span
      className={`tilli tilli--${mood}${flip ? ' tilli--flip' : ''}${still ? ' tilli--still' : ''} ${className ?? ''}`}
      style={vars}
      // Static, trusted markup generated by tilliSvg — no user input reaches it.
      dangerouslySetInnerHTML={{ __html: html }}
    />
  );
}
